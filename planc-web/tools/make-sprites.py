#!/usr/bin/env python3
"""
make-sprites.py — turn ../assets-svg/sprites.svg into js/sprites.js

Why a JS file and not fetch(): index.html must open from file:// with no
server (project rule), and fetch() is blocked on file:// in Chromium.

Why currentColor: every asset is baked black (#000000). The dark level
swaps --ink/--paper by flipping the inherited `color`, so sprites must
paint with currentColor to invert for free — the "state both sides"
CSS rule handled once, at the source.
"""
import json, pathlib, re

HERE = pathlib.Path(__file__).parent
SRC  = HERE.parent.parent / "assets-svg" / "sprites.svg"
OUT  = HERE.parent / "js" / "sprites.js"

svg = SRC.read_text(encoding="utf-8")
svg = svg.replace('fill="#000000"', 'fill="currentColor"')
# safety net: any other hard-coded black
svg = re.sub(r'fill="#000\b"', 'fill="currentColor"', svg)
svg = re.sub(r"\r\n?", "\n", svg)

count = svg.count("<symbol")
OUT.write_text(
    "/* generated by tools/make-sprites.py — do not edit by hand */\n"
    "window.PLANC_SPRITES = " + json.dumps(svg, ensure_ascii=False) + ";\n"
    "document.body.insertAdjacentHTML('afterbegin', PLANC_SPRITES);\n",
    encoding="utf-8",
)
print(f"wrote {OUT}  ({OUT.stat().st_size:,} bytes, {count} symbols)")
